from __future__ import annotations

"""Corners were the weakest team-prop (delta -0.003/-0.005, 4/5 folds).
Hypothesis: corners are generated by shot volume / territorial dominance, so
cross-signals (shots-for, xG-for rollings) should add to corners-only history.

A/B on the same folds: BASE (corners features only, deployed recipe) vs
AUGMENTED (+ shots & xG for/against rollings). Same NB scoring, league baseline.
"""

import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import nbinom
from sklearn.linear_model import PoissonRegressor

ROOT = Path(__file__).resolve().parents[1]
FOUND = ROOT / "data/processed/foundation_big5_multi_season.csv"
W = (5, 10, 19)
TEST_SEASONS = ["2021-2022", "2022-2023", "2023-2024", "2024-2025", "2025-2026"]
LINES = [8.5, 9.5, 10.5]


def prob_over(lam, line, disp):
    k = int(np.floor(line))
    lam = np.clip(lam, 0.2, 40.0)
    r = lam / (disp - 1.0)
    return 1.0 - nbinom.cdf(k, r, 1.0 / disp)


def bll(y, p):
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return float(-(y * np.log(p) + (1 - y) * np.log(1 - p)).mean())


def build_long(m: pd.DataFrame, cols: dict[str, tuple[str, str]]) -> pd.DataFrame:
    """cols: name -> (home_col, away_col); emits <name>_for/_against per side."""
    rows = []
    for r in m.itertuples(index=False):
        base = dict(match_id=r.match_id, date=r.date, team=r.home_team, opp=r.away_team, is_home=1)
        for n, (hc, ac) in cols.items():
            base[f"{n}_for"], base[f"{n}_against"] = getattr(r, hc), getattr(r, ac)
        rows.append(base)
        base = dict(match_id=r.match_id, date=r.date, team=r.away_team, opp=r.home_team, is_home=0)
        for n, (hc, ac) in cols.items():
            base[f"{n}_for"], base[f"{n}_against"] = getattr(r, ac), getattr(r, hc)
        rows.append(base)
    lr = pd.DataFrame(rows).sort_values(["team", "date", "match_id"])
    feat_cols = []
    for n in cols:
        for side in ["for", "against"]:
            c = f"{n}_{side}"
            for w in W:
                lr[f"{c}_r{w}"] = (lr.groupby("team", group_keys=False)[c]
                                   .apply(lambda s: s.shift(1).rolling(w, min_periods=3).mean()))
                feat_cols.append(f"{c}_r{w}")
            lr[f"{c}_ewm"] = (lr.groupby("team", group_keys=False)[c]
                              .apply(lambda s: s.shift(1).ewm(halflife=5, min_periods=3).mean()))
            feat_cols.append(f"{c}_ewm")
    against_feats = [f for f in feat_cols if "_against_" in f]
    opp = lr[["match_id", "team"] + against_feats].rename(
        columns={"team": "opp", **{c: f"opp_{c}" for c in against_feats}})
    return lr.merge(opp, on=["match_id", "opp"], how="left")


def run(tag: str, m: pd.DataFrame, cols: dict) -> None:
    lr = build_long(m, cols)
    feats = []
    for n in cols:
        feats += [f"{n}_for_r{w}" for w in W] + [f"{n}_for_ewm"]
        feats += [f"opp_{n}_against_r{w}" for w in W] + [f"opp_{n}_against_ewm"]
    feats += ["is_home"]
    res = {ln: {"m": [], "b": []} for ln in LINES}
    for s in TEST_SEASONS:
        te_m = m[m.season == s]
        s_start = te_m.date.min()
        tr = lr[lr.date < s_start].dropna(subset=feats + ["corners_for"])
        reg = PoissonRegressor(alpha=0.1, max_iter=1000).fit(tr[feats], tr["corners_for"].clip(lower=0))
        te = lr[lr.match_id.isin(set(te_m.match_id))].dropna(subset=feats).copy()
        te["pred"] = np.clip(reg.predict(te[feats]), 0.1, 25)
        pv = te.pivot_table(index="match_id", columns="is_home", values="pred").dropna()
        tot = pv[1] + pv[0]
        tr_tot = m[m.date < s_start]
        tt = (tr_tot["home_corners"] + tr_tot["away_corners"]).astype(float)
        disp = float(np.clip(tt.var() / max(tt.mean(), 1e-9), 1.11, 3.0))
        lg = tr_tot.assign(tot=tt).groupby("competition")["tot"].mean()
        tei = te_m.set_index("match_id").loc[tot.index]
        base_v = tei["competition"].map(lg).fillna(float(tt.mean())).to_numpy()
        act = tei[["home_corners", "away_corners"]].sum(axis=1).astype(float)
        for ln in LINES:
            y = (act > ln).astype(float).to_numpy()
            res[ln]["m"].append((bll(y, prob_over(tot.to_numpy(), ln, disp)), len(y), s))
            res[ln]["b"].append((bll(y, prob_over(base_v, ln, disp)), len(y), s))
    pool = lambda a: sum(x * n for x, n, _ in a) / sum(n for _, n, _ in a)
    for ln in LINES:
        folds = " ".join(f"{s[2][-2:]}{'+' if s[0] < b[0] else '-'}" for s, b in zip(res[ln]["m"], res[ln]["b"]))
        print(f"  {tag} O/U {ln}: LL {pool(res[ln]['m']):.4f} vs base {pool(res[ln]['b']):.4f} "
              f"delta {pool(res[ln]['m'])-pool(res[ln]['b']):+.4f}  [{folds}]", flush=True)


def main() -> None:
    df = pd.read_csv(FOUND, low_memory=False)
    df["date"] = pd.to_datetime(df["date"], errors="coerce")
    df = df[df["season"] >= "2014-2015"]
    need = ["home_corners", "away_corners", "home_shots", "away_shots", "date"]
    m = df.dropna(subset=need).copy()
    for c in ["home_corners", "away_corners", "home_shots", "away_shots", "home_xg", "away_xg"]:
        if c in m.columns:
            m[c] = pd.to_numeric(m[c], errors="coerce")
    m = m.dropna(subset=["home_corners", "away_corners", "home_shots", "away_shots"])

    t0 = time.time()
    print("BASE (corners only):")
    run("BASE", m, {"corners": ("home_corners", "away_corners")})
    print(f"\nAUG +shots ({time.time()-t0:.0f}s):")
    run("AUG-S", m, {"corners": ("home_corners", "away_corners"),
                     "shots": ("home_shots", "away_shots")})
    mx = m.dropna(subset=["home_xg", "away_xg"])
    print(f"\nAUG +shots +xG (xG subset n={len(mx)}, {time.time()-t0:.0f}s):")
    run("AUG-SX", mx, {"corners": ("home_corners", "away_corners"),
                       "shots": ("home_shots", "away_shots"),
                       "xg": ("home_xg", "away_xg")})


if __name__ == "__main__":
    main()
